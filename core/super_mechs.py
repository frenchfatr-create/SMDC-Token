from decimal import Decimal


# ============================================================
# ТОКЕНЫ ЗА РУБЛИ
# ============================================================
#
# 50 ₽ = 7 500 токенов
# 100 ₽ = 15 000 токенов
# 150 ₽ = 22 500 токенов
# 500 ₽ = 75 000 токенов
#
# Курс:
# 1 ₽ = 150 токенов
#
# Минимум:
# 50 ₽
#
RUB_PACKS = [
    (50, 7500),
]


def rub_tokens(amount: int) -> int:
    """
    Возвращает количество токенов за указанную сумму в рублях.

    1 ₽ = 150 токенов
    Минимальная сумма = 50 ₽
    """

    if amount < 50:
        raise ValueError(
            "Минимальная сумма — 50 ₽"
        )

    return int(amount) * 150


