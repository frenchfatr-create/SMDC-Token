# ============================================================

def silver_total(
    quantity: int
) -> Decimal:

    quantity = int(quantity)

    if quantity < 10:
        raise ValueError(
            "Минимальный заказ — 10 Silver Boxes"
        )

    return (
        Decimal(quantity)
        * Decimal("1.5")
    )