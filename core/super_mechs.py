# ============================================================
# SILVER BOXES
# ============================================================

def silver_total(quantity: int) -> Decimal:
    """
    Стоимость Silver Boxes.

    1 Silver Box = 1.5 ₽
    Минимальный заказ = 10 шт.
    """

    if quantity < 10:
        raise ValueError(
            "Минимальный заказ — 10 Silver Boxes"
        )

    return Decimal(quantity) * Decimal("1.5")