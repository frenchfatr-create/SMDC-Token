from decimal import Decimal


# ============================================================
# ТОКЕНЫ ЗА РУБЛИ
# ============================================================

# 50 ₽ = 7 500 токенов
# 100 ₽ = 15 000 токенов
# 150 ₽ = 22 500 токенов
# 500 ₽ = 75 000 токенов

RUB_PACKS = [
    (50, 7500),
]


def rub_tokens(amount: int) -> int:
    """
    Расчёт токенов за рубли.

    1 ₽ = 150 токенов.
    Минимальная сумма — 50 ₽.
    """

    if amount < 50:
        raise ValueError(
            "Минимальная сумма — 50 ₽"
        )

    return int(amount) * 150


# ============================================================
# ТОКЕНЫ ЗА TELEGRAM STARS
# ============================================================

# ПРАЙС ИМЕННО КАК НА СКРИНЕ:
#
# 25 ⭐  = 7 500 токенов
# 50 ⭐  = 15 000 токенов
# 75 ⭐  = 22 500 токенов
# 100 ⭐ = 30 000 токенов
# 175 ⭐ = 37 500 токенов
# 250 ⭐ = 45 000 токенов

STAR_PACKS = [
    (25, 7500),
    (50, 15000),
    (75, 22500),
    (100, 30000),
    (175, 37500),
    (250, 45000),
]


def star_tokens(stars: int) -> int:
    """
    Возвращает количество токенов
    для выбранного тарифа Stars.

    Используются именно фиксированные тарифы
    из STAR_PACKS.
    """

    prices = dict(STAR_PACKS)

    if stars not in prices:
        raise ValueError(
            "Выберите доступный тариф Stars."
        )

    return prices[stars]


