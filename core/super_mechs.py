STAR_PACKS = [
    (25, 7500),
    (50, 15000),
    (75, 22500),
    (100, 30000),
    (175, 37500),
    (250, 45000),
    (300, 50000),
]


def star_tokens(stars: int) -> int:
    """
    Расчёт токенов за Stars.

    До 100 ⭐:
        1 ⭐ = 300 токенов

    После 100 ⭐:
        каждая дополнительная ⭐ = 100 токенов

    Поэтому:

    25  ⭐ = 7 500
    50  ⭐ = 15 000
    75  ⭐ = 22 500
    100 ⭐ = 30 000
    175 ⭐ = 37 500
    250 ⭐ = 45 000
    300 ⭐ = 50 000

    Можно вводить и другие значения,
    например 125, 200, 300, 500 и т.д.
    """

    stars = int(stars)

    if stars <= 0:
        raise ValueError(
            "Количество Stars должно быть больше 0."
        )

    if stars <= 100:
        return stars * 300

    return 30000 + (
        stars - 100
    ) * 100


