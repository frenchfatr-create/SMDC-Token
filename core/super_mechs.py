# ТОКЕНЫ ЗА РУБЛИ
# ============================================================

RUB_PACKS = [
    (50, 7500),
]


def rub_tokens(amount: int) -> int:
    amount = int(amount)

    if amount < 50:
        raise ValueError(
            "Минимальная сумма — 50 ₽"
        )

    return amount * 150


# ============================================================
# ТОКЕНЫ ЗА TELEGRAM STARS
# ============================================================

STAR_PACKS = [
    (25, 7500),
    (50, 15000),
    (75, 22500),
    (100, 30000),
    (175, 37500),
    (250, 45000),
    (300, 50000),
]


def star_tokens(stars: int) -> int:
    """
    Расчёт количества Super Mechs токенов за Telegram Stars.

    Фиксированные наборы:

        25  ⭐ → 7 500 токенов
        50  ⭐ → 15 000 токенов
        75  ⭐ → 22 500 токенов
        100 ⭐ → 30 000 токенов
        175 ⭐ → 37 500 токенов
        250 ⭐ → 45 000 токенов
        300 ⭐ → 50 000 токенов

    Для значений, которых нет в STAR_PACKS:

        до 100 ⭐:
            1 ⭐ = 300 токенов

        после 100 ⭐:
            30 000 + 100 токенов за каждую
            звезду сверх 100.
    """

    stars = int(stars)

    if stars <= 0:
        raise ValueError(
            "Количество Stars должно быть больше 0."
        )

    # Сначала проверяем готовые наборы.
    for pack_stars, tokens in STAR_PACKS:
        if stars == pack_stars:
            return tokens

    # Значения до 100 Stars.
    if stars <= 100:
        return stars * 300

    # Значения больше 100 Stars.
    return 30000 + (
        stars - 100
    ) * 100


